<#
.SYNOPSIS
Compiles source modules and reports the compiler's diagnostics.

.DESCRIPTION
Lokn shows a source module's compile errors only inside its own window. This builds
the module's generated project with the same language settings and references, so
the errors are readable from a terminal. Exits non-zero when a module does not
compile.

A clean build does not prove the module loaded: it cannot catch a duplicate module
ID or an exception thrown from Register or Start. Those appear in Lokn's notice bar.

Every module project imports the Directory.Build.props that Lokn writes into its
per-user modules folder at startup, so Lokn must have been started at least once
since hot reload was added. A module folder outside that folder imports it by path,
as Lokn's own generated project does.

.EXAMPLE
pwsh scripts/check-module.ps1 -Name Notes

.EXAMPLE
# Every module a project keeps in its .lokn\modules, or one with -Name.
pwsh scripts/check-module.ps1 -Project D:\src\my-game
pwsh scripts/check-module.ps1 -Project D:\src\my-game -Name SceneLab
#>
param(
	# The module's folder name. Optional with -Project, which then checks every module of the project.
	[string] $Name,

	# The modules folder. Defaults to the one Lokn watches, or the project's .lokn\modules with -Project.
	[string] $Root,

	# A project directory whose .lokn\modules holds the modules to check.
	[string] $Project
)

. "$PSScriptRoot\common.ps1"

$userRoot = Join-Path $env:LOCALAPPDATA 'Lokn\modules'
$settings = Join-Path $userRoot 'Directory.Build.props'
if ( $Project )
{
	if ( $Root )
	{
		throw 'Pass -Project or -Root, not both.'
	}

	$Root = Join-Path $Project '.lokn\modules'
}
elseif ( -not $Root )
{
	$Root = $userRoot
}

if ( -not $Name -and -not $Project )
{
	throw 'Pass -Name, -Project, or both.'
}

if ( -not ( Test-Path $settings ) )
{
	Write-Host "Missing $settings. Start Lokn once (pwsh scripts/run.ps1) so it generates the editor project files."
	exit 1
}

if ( $Name )
{
	$directories = @( Join-Path $Root $Name )
}
else
{
	# Lokn loads each subfolder holding C# files as one module.
	$directories = @( Get-ChildItem $Root -Directory -ErrorAction Ignore | Where-Object { Get-ChildItem $_.FullName -Filter '*.cs' -Recurse | Select-Object -First 1 } | ForEach-Object FullName )
	if ( $directories.Count -eq 0 )
	{
		Write-Host "No modules in $Root"
		exit 1
	}
}

$failed = @()
foreach ( $directory in $directories )
{
	$module = Split-Path -Leaf $directory
	if ( -not ( Test-Path $directory ) )
	{
		Write-Host "No such module folder: $directory"
		$failed += $module
		continue
	}

	# Lokn writes this project the first time it sees the folder; create the same one if it has not run since.
	$file = Get-ChildItem $directory -Filter '*.csproj' | Select-Object -First 1
	if ( -not $file )
	{
		$relative = [IO.Path]::GetRelativePath( $userRoot, $directory )
		$isInside = -not $relative.StartsWith( '..' ) -and -not [IO.Path]::IsPathRooted( $relative )
		$text = if ( $isInside )
		{
			"<!-- Generated by Lokn for editor IntelliSense. Lokn compiles this directory's .cs files itself. -->`r`n<Project Sdk=`"Microsoft.NET.Sdk`" />`r`n"
		}
		else
		{
			# MSBuild finds Directory.Build.props only by walking up, so a module elsewhere imports it by path.
			$escaped = [Security.SecurityElement]::Escape( $settings )
			"<!-- Generated by Lokn for editor IntelliSense. Lokn compiles this directory's .cs files itself. -->`r`n<Project>`r`n`t<Import Project=`"$escaped`" />`r`n`t<Import Project=`"Sdk.props`" Sdk=`"Microsoft.NET.Sdk`" />`r`n`t<Import Project=`"Sdk.targets`" Sdk=`"Microsoft.NET.Sdk`" />`r`n</Project>`r`n"
		}

		$path = Join-Path $directory "$module.csproj"
		[IO.File]::WriteAllText( $path, $text )
		$file = Get-Item $path
	}

	dotnet build $file.FullName -nologo -v q
	if ( $LASTEXITCODE -ne 0 )
	{
		$failed += $module
	}
}

if ( $failed.Count -gt 0 )
{
	Write-Host "MODULE DOES NOT COMPILE: $( $failed -join ', ' )"
	exit 1
}

Write-Host "MODULE COMPILES: $( ( $directories | ForEach-Object { Split-Path -Leaf $_ } ) -join ', ' )"
