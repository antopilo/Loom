using System.Security;

namespace Lokn.Modules.Hotload;

/// <summary>Writes the project files for editor IntelliSense and the authoring guide for coding agents.</summary>
public sealed partial class HotloadModule
{
	/// <summary>Defines the shared settings file MSBuild imports into every project below the modules directory.</summary>
	private const string EditorSettingsFile = "Directory.Build.props";

	/// <summary>Defines the file name coding agents read for instructions in a working directory.</summary>
	private const string GuideFile = "AGENTS.md";

	/// <summary>Defines the embedded resource holding the guide, authored in ModuleGuide.md.</summary>
	private const string GuideResource = "ModuleGuide.md";

	/// <summary>Defines the project written into a module directory; its settings come from the shared file.</summary>
	private const string ProjectText = """
		<!-- Generated by Lokn for editor IntelliSense. Lokn compiles this directory's .cs files itself. -->
		<Project Sdk="Microsoft.NET.Sdk" />

		""";

	/// <summary>Writes the shared settings pointing editors at the running application's Goo and Lokn.Core.</summary>
	private void EnsureEditorSettings()
	{
		var binaries = SecurityElement.Escape( AppContext.BaseDirectory );

		// Build output goes to the temp directory so generated .cs files never join a module's sources.
		var text = $"""
			<!-- Generated by Lokn at startup for editor IntelliSense; edits are overwritten. -->
			<Project>
				<PropertyGroup>
					<TargetFramework>net10.0</TargetFramework>
					<LangVersion>14</LangVersion>
					<ImplicitUsings>enable</ImplicitUsings>
					<Nullable>enable</Nullable>
					<BaseIntermediateOutputPath>$([System.IO.Path]::GetTempPath())Lokn\modules\$(MSBuildProjectName)\obj\</BaseIntermediateOutputPath>
					<BaseOutputPath>$([System.IO.Path]::GetTempPath())Lokn\modules\$(MSBuildProjectName)\bin\</BaseOutputPath>
				</PropertyGroup>
				<ItemGroup>
					<Reference Include="{binaries}Lokn.Core.dll" />
					<Reference Include="{binaries}Goo.dll" />
				</ItemGroup>
			</Project>

			""";

		WriteChanged( Path.Combine( _path, EditorSettingsFile ), text );
	}

	/// <summary>Writes the authoring guide that tells coding agents working in the directory how modules behave.</summary>
	private void EnsureGuide()
	{
		var guide = typeof( HotloadModule ).Assembly.GetManifestResourceStream( GuideResource )!;
		WriteChanged( Path.Combine( _path, GuideFile ), new StreamReader( guide ).ReadToEnd() );
	}

	/// <summary>Writes a generated file only when its text differs, so open editors do not reload at each startup.</summary>
	private static void WriteChanged( string file, string text )
	{
		if ( File.Exists( file ) && File.ReadAllText( file ) == text )
			return;

		File.WriteAllText( file, text );
	}

	/// <summary>Writes a project into a module directory that has none, leaving an existing one untouched.</summary>
	/// <remarks>A module outside the per-user directory imports its shared settings by path, since MSBuild only finds them by walking up.</remarks>
	private void EnsureProject( string directory )
	{
		if ( Directory.EnumerateFiles( directory, "*.csproj" ).Any() )
			return;

		var isInside = Path.GetRelativePath( _path, directory ) is var relative && !relative.StartsWith( "..", StringComparison.Ordinal ) && !Path.IsPathRooted( relative );
		var text = isInside ? ProjectText : $"""
			<!-- Generated by Lokn for editor IntelliSense. Lokn compiles this directory's .cs files itself. -->
			<Project>
				<Import Project="{SecurityElement.Escape( Path.Combine( _path, EditorSettingsFile ) )}" />
				<Import Project="Sdk.props" Sdk="Microsoft.NET.Sdk" />
				<Import Project="Sdk.targets" Sdk="Microsoft.NET.Sdk" />
			</Project>

			""";
		File.WriteAllText( Path.Combine( directory, Path.GetFileName( directory ) + ".csproj" ), text );
	}
}
